"""Extracts the design boards' own inline SVG icons into assets/icons/ (plan section 0.4:
"the boards' own icons, never Material look-alikes") and writes a catalog of which boards use
each one: docs/new-ui/ICONS.md.

    python -I tool/new_ui/extract_icons.py

Identical icons (same markup after normalising whitespace and ids) are written once. Names
come from the nearest aria-label around the icon on the board (e.g. "Save" → save.svg);
icons without one get icon_<n>.svg and should be renamed when first used. The brand mark
(viewBox "40 28 370 292") lives in assets/brand/ and is skipped here.
"""
import os
import re
from collections import OrderedDict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
REF = os.path.join(ROOT, 'docs', 'new-ui', 'reference')
OUT = os.path.join(ROOT, 'assets', 'icons')
CATALOG = os.path.join(ROOT, 'docs', 'new-ui', 'ICONS.md')

SVG_RE = re.compile(r'<svg\b[^>]*>.*?</svg>', re.S)
LABEL_RE = re.compile(r'aria-label="([^"]+)"')


def normalise(svg):
    svg = re.sub(r'\s+', ' ', svg)
    svg = re.sub(r'\s(style|class|aria-hidden|width|height|role|aria-label)="[^"]*"', '', svg)
    return svg.strip()


def slug(text):
    s = re.sub(r'[^a-z0-9]+', '_', text.lower()).strip('_')
    return s[:40] or 'icon'


icons = OrderedDict()  # normalised svg -> {name, boards, labels}
for fname in sorted(os.listdir(REF)):
    if not fname.endswith('.dc.html') or fname.startswith('Note'):
        continue
    board = fname[:-8]
    html = open(os.path.join(REF, fname), encoding='utf-8').read()
    for m in SVG_RE.finditer(html):
        svg = m.group(0)
        if 'viewBox="40 28 370 292"' in svg:
            continue  # brand mark
        key = normalise(svg)
        before = html[max(0, m.start() - 400):m.start()]
        labels = LABEL_RE.findall(before + svg)
        entry = icons.setdefault(key, {'boards': [], 'labels': []})
        if board not in entry['boards']:
            entry['boards'].append(board)
        if labels and labels[-1] not in entry['labels']:
            entry['labels'].append(labels[-1])

os.makedirs(OUT, exist_ok=True)
used = set()
rows = []
for n, (key, entry) in enumerate(icons.items(), 1):
    base = slug(entry['labels'][0]) if entry['labels'] else f'icon_{n}'
    name, k = base, 2
    while name in used:
        name, k = f'{base}_{k}', k + 1
    used.add(name)
    svg = key if 'xmlns=' in key else key.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"', 1)
    with open(os.path.join(OUT, f'{name}.svg'), 'w', encoding='utf-8') as f:
        f.write(svg + '\n')
    rows.append(f"| ![{name}](../../assets/icons/{name}.svg) | `assets/icons/{name}.svg` | "
                f"{', '.join(entry['labels']) or '—'} | {', '.join(entry['boards'])} |")

with open(CATALOG, 'w', encoding='utf-8') as f:
    f.write('# Design icons\n\n')
    f.write('Generated by `tool/new_ui/extract_icons.py` from the boards in `reference/`. '
            'Use these files (with `flutter_svg`), not Material icons. Rename an `icon_<n>` '
            'file to what it shows the first time you use it, and update this table.\n\n')
    f.write('| Icon | File | Labels on the boards | Boards |\n|---|---|---|---|\n')
    f.write('\n'.join(rows) + '\n')
print(f'{len(icons)} unique icons -> {OUT}; catalog -> {CATALOG}')
